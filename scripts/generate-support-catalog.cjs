// JSON is authoritative; the generated script supports offline HTML.
const fs = require('fs'), path = require('path'), root = path.resolve(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'shared/support-definitions.json'), 'utf8'));
const output = '// Generated by scripts/generate-support-catalog.cjs. Do not edit.\nwindow.MKEFSupportDefinitions = ' + JSON.stringify(data) + ';\n';
const target = path.join(root, 'shared/support-catalog.js');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') !== output) throw new Error('Support catalog is out of date.');
} else fs.writeFileSync(target, output);
