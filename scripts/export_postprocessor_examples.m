function export_postprocessor_examples(destination)
%EXPORT_POSTPROCESSOR_EXAMPLES Rebuild the four handbook results with Octave.
if nargin < 1, destination = fullfile('output', 'postprocessor-examples'); end
setup();
if ~exist(destination, 'dir'), mkdir(destination); end
quiet = struct('verbose', false, 'plotting', false);
problem = StructFEProblem(fullfile('examples', 'cases', 'ANSYSBeamStatic01.txt'), quiet);
exportPostprocessorData(problem.GetAnalysisModel(), problem.RunStatic(), ...
    fullfile(destination, 'static-frame.json'), struct('title', 'Статическая рама', ...
    'lengthUnit', 'm', 'forceUnit', 'N', 'momentUnit', 'N*m', 'stressUnit', 'Pa', 'prettyPrint', true));
problem = StructFEProblem(fullfile('examples', 'cases', 'CaseBeam.txt'), quiet);
exportPostprocessorData(problem.GetAnalysisModel(), problem.RunModal(), ...
    fullfile(destination, 'modal-frame.json'), struct('title', 'Формы колебаний', ...
    'lengthUnit', 'm', 'prettyPrint', true));
options = struct('title', 'Переходный отклик', 'lengthUnit', 'm', ...
    'forceUnit', 'N', 'momentUnit', 'N*m', 'timeUnit', 's', 'prettyPrint', true, ...
    'transientFields', {{'displacements', 'velocities', 'accelerations', ...
    'loadHistory', 'reactions', 'spectrum'}}, 'timeStride', 1);
exportPostprocessorData(problem.GetAnalysisModel(), problem.RunTransient(1e-4, 1e-2, 3, 2), ...
    fullfile(destination, 'transient-history.json'), options);
problem = StructFEProblem(fullfile('examples', 'cases', 'CasePinnedPortalUniform.txt'), quiet);
exportPostprocessorData(problem.GetAnalysisModel(), problem.RunStatic(), ...
    fullfile(destination, 'pinned-portal-uniform.json'));
end
